const styles = StyleSheet.create({
  page: { padding: 34, fontFamily: "Helvetica", fontSize: 8, color: "#173c36" },
  title: { fontSize: 18, marginBottom: 6, fontWeight: 700 },
  subtitle: { color: "#63756e", marginBottom: 8, fontSize: 8 },
  banner: { backgroundColor: "#fff4d7", color: "#74510a", padding: 8, marginBottom: 11, fontSize: 8 },
  sectionTitle: { marginTop: 8, marginBottom: 4, fontSize: 10, fontWeight: 700 },
  row: { flexDirection: "row", borderBottomWidth: 0.5, borderBottomColor: "#dfe7e2", paddingVertical: 4 },
  header: { backgroundColor: "#eaf3ef", fontWeight: 700 },
  notes: { marginTop: 12, color: "#667670", fontSize: 7, lineHeight: 1.4 },
});

type Detail = {
  date: string;
  point: string;
  zone: string;
  category: string;
  weightKg: number;
  simulated: boolean;
  estimate: number;
};
function validDate(value: string | null) {
  if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return null;
  const date = new Date(`${value}T00:00:00.000Z`);
  return !Number.isNaN(date.valueOf()) && date.toISOString().slice(0, 10) === value ? value : null;
}
function buildPdf(
  rows: Detail[],
  from: string,
  to: string,
  actor: string,
  generatedAt: string,
  totals: { kg: number; estimate: number },
  byZone: Array<[string, number]>,
  byCategory: Array<[string, number, number]>,
  filterLabel: string,
) {
  const detailColumns = [
    { title: "Date", width: "10%" },
    { title: "Point", width: "12%" },
    { title: "Zone", width: "18%" },
    { title: "Material", width: "16%" },
    { title: "Weight kg", width: "12%" },
    { title: "Source", width: "16%" },
    { title: "CO₂e est. kg", width: "16%" },
  ];
  const detailHeader = React.createElement(
    View,
    { style: [styles.row, styles.header] },
    ...detailColumns.map((column, index) =>
      React.createElement(Text, { key: index, style: { width: column.width } }, column.title),
    ),
  );
  const summaryRows = [
    React.createElement(
      Text,
      { key: "total", style: styles.subtitle },
      `Total recorded material: ${totals.kg.toFixed(2)} kg · Provisional recyclable CO₂e estimate: ${totals.estimate.toFixed(2)} kg`,
    ),
    ...byZone.map(([zone, kg]) =>
      React.createElement(
        Text,
        { key: `zone-${zone}`, style: styles.subtitle },
        `Zone · ${zone}: ${kg.toFixed(2)} kg`,
      ),
    ),
    ...byCategory.map(([category, kg, estimate]) =>
      React.createElement(
        Text,
        { key: `category-${category}`, style: styles.subtitle },
        `Category · ${category}: ${kg.toFixed(2)} kg · estimated CO₂e ${estimate.toFixed(2)} kg`,
      ),
    ),
  ];
  return React.createElement(
    Document,
    null,
    React.createElement(
      Page,
      { size: "A4", orientation: "landscape", style: styles.page },
      React.createElement(Text, { style: styles.title }, "WasteOps · Collection and recycling report"),
      React.createElement(
        Text,
        { style: styles.subtitle },
        `Reporting window: ${from} to ${to} UTC · Filter: ${filterLabel}`,
      ),
      React.createElement(
        Text,
        { style: styles.subtitle },
        `Generated at: ${generatedAt} UTC · Generated by: ${actor} · ${rows.length} material rows`,
      ),
      React.createElement(
        Text,
        { style: styles.banner },
        "SIMULATED records are fictional demonstrations. CO₂e is a provisional estimate using 2.5 kg CO₂e/kg for plastic, paper, glass and metal only; it is not measured impact.",
      ),
      React.createElement(Text, { style: styles.sectionTitle }, "Summary by zone and material"),
      ...summaryRows,
      React.createElement(Text, { style: styles.sectionTitle }, "Completed collection details"),
      detailHeader,
      ...rows
        .slice(0, 2000)
        .map((row, index) =>
          React.createElement(
            View,
            { key: `${row.point}-${row.date}-${row.category}-${index}`, style: styles.row },
            React.createElement(Text, { style: { width: "10%" } }, row.date),
            React.createElement(Text, { style: { width: "12%" } }, row.point),
            React.createElement(Text, { style: { width: "18%" } }, row.zone),
            React.createElement(Text, { style: { width: "16%" } }, row.category),
            React.createElement(Text, { style: { width: "12%" } }, row.weightKg.toFixed(2)),
            React.createElement(Text, { style: { width: "16%" } }, row.simulated ? "SIMULATED" : "RECORDED"),
            React.createElement(Text, { style: { width: "16%" } }, row.estimate.toFixed(2)),
          ),
        ),
      React.createElement(
        Text,
        { style: styles.notes },
        rows.length > 2000
          ? "PDF detail is limited to the first 2,000 material rows; summary totals cover the full result. Download CSV for every matching row."
          : "Weight is manually recorded in kilograms. Diversion is not equivalent to verified final recovery. CO₂e is an estimate, not measured impact. Generated by the WasteOps software MVP.",
      ),
    ),
  );
}

export async function GET(request: Request) {
  let actor;
  try {
    actor = await requireActor(["ADMIN", "SUPERVISOR"]);
  } catch (error) {
    const status =
      error instanceof AuthorizationError ? (error.message.startsWith("Please sign in") ? 401 : 403) : 500;
    return NextResponse.json(
      {
        error:
          status === 401
            ? "Sign-in required."
            : status === 403
              ? "Not authorized."
              : "Report service unavailable.",
      },
      { status, headers: { "Cache-Control": "no-store" } },
    );
  }
  const url = new URL(request.url);
  const format = url.searchParams.get("format");
  const from = validDate(url.searchParams.get("from"));
  const to = validDate(url.searchParams.get("to"));
  const zoneRaw = url.searchParams.get("zone")?.trim() ?? "";
  const categoryRaw = url.searchParams.get("category") ?? "";
  if (
    zoneRaw.length > 60 ||
    (categoryRaw && !wasteCategories.includes(categoryRaw as (typeof wasteCategories)[number]))
  )
    return NextResponse.json(
      { error: "Choose a valid zone and waste category." },
      { status: 400, headers: { "Cache-Control": "no-store" } },
    );
  const zone = zoneRaw || undefined;
  const category = (categoryRaw || undefined) as WasteCategory | undefined;
  if (!from || !to || to < from)
    return NextResponse.json(
      { error: "Choose a valid reporting window." },
      { status: 400, headers: { "Cache-Control": "no-store" } },
    );
  const start = new Date(`${from}T00:00:00.000Z`);
  const end = new Date(Date.parse(`${to}T00:00:00.000Z`) + 86400000);
  if (end.getTime() - start.getTime() > 366 * 86400000)
    return NextResponse.json(
      { error: "Choose a period no longer than one year." },
      { status: 400, headers: { "Cache-Control": "no-store" } },
    );
  if (format !== "csv" && format !== "pdf")
    return NextResponse.json(
      { error: "Choose csv or pdf." },
      { status: 400, headers: { "Cache-Control": "no-store" } },
    );
  try {
    const collections = await prisma.collection.findMany({
      where: {
        organizationId: actor.organizationId,
        status: CollectionStatus.COMPLETED,
        completedAt: { gte: start, lt: end },
        ...(zone ? { point: { zone } } : {}),
        ...(category ? { materials: { some: { category } } } : {}),
      },
      include: {
        point: { select: { code: true, zone: true } },
        materials: { where: category ? { category } : undefined },
      },
      orderBy: { completedAt: "asc" },
      take: 10001,
    });
    if (collections.length > 10000)
      return NextResponse.json(
        { error: "This period is too large; select a narrower window." },
        { status: 413, headers: { "Cache-Control": "no-store" } },
      );
    const rows: Detail[] = collections.flatMap((collection) =>
      collection.materials.map((material) => ({
        date: collection.completedAt?.toISOString().slice(0, 10) ?? "",
        point: collection.point.code,
        zone: collection.point.zone,
        category: material.category,
        weightKg: material.weightKg,
        simulated: collection.isSimulated || collection.source === "SIMULATED",
        estimate: ["PLASTIC", "PAPER", "GLASS", "METAL"].includes(material.category)
          ? material.weightKg * 2.5
          : 0,
      })),
    );
    const zoneTotals = new Map<string, number>();
    const categoryTotals = new Map<string, { kg: number; estimate: number }>();
    let totalKg = 0;
    let totalEstimate = 0;
    for (const row of rows) {
      totalKg += row.weightKg;
      totalEstimate += row.estimate;
      zoneTotals.set(row.zone, (zoneTotals.get(row.zone) ?? 0) + row.weightKg);
      const current = categoryTotals.get(row.category) ?? { kg: 0, estimate: 0 };
      categoryTotals.set(row.category, {
        kg: current.kg + row.weightKg,
        estimate: current.estimate + row.estimate,
      });
    }
    const generatedAt = new Date().toISOString();
    const filterLabel = [
      zone ? `zone=${zone}` : "all zones",
      category ? `category=${category}` : "all categories",
    ].join("; ");
    if (format === "csv") {
      const columns = [
        "record_type",
        "completed_date_utc",
        "point_code",
        "zone",
        "waste_category",
        "weight_kg",
        "source",
        "estimated_co2e_kg_provisional",
        "window_start_utc",
        "window_end_utc",
        "generated_at_utc",
        "generated_by",
      ];
      const metadata = ["REPORT_METADATA", "", "", "", "", "", "", "", from, to, generatedAt, actor.fullName];
      const detailRows = rows.map((row) => [
        "DETAIL",
        row.date,
        row.point,
        row.zone,
        row.category,
        row.weightKg.toFixed(2),
        row.simulated ? "SIMULATED" : "RECORDED",
        row.estimate.toFixed(2),
        "",
        "",
        "",
        "",
      ]);
      const summaryZoneRows = [...zoneTotals]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([name, kg]) => ["ZONE_SUMMARY", "", "", name, "", kg.toFixed(2), "", "", "", "", "", ""]);
      const summaryCategoryRows = [...categoryTotals]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([name, value]) => [
          "CATEGORY_SUMMARY",
          "",
          "",
          "",
          name,
          value.kg.toFixed(2),
          "",
          value.estimate.toFixed(2),
          "",
          "",
          "",
          "",
        ]);
      const summaryTotal = [
        "TOTAL_SUMMARY",
        "",
        "",
        "",
        "",
        totalKg.toFixed(2),
        "",
        totalEstimate.toFixed(2),
        "",
        "",
        "",
        "",
      ];
      const csv = [columns, metadata, ...detailRows, ...summaryZoneRows, ...summaryCategoryRows, summaryTotal]
        .map((row) => row.map((cell) => csvCell(String(cell))).join(","))
        .join("\r\n");
      await writeAudit(prisma, {
        organizationId: actor.organizationId,
        actorId: actor.id,
        action: "report.export.csv",
        entityType: "Report",
        metadata: { from, to, zone: zone ?? null, category: category ?? null, rowCount: rows.length },
      });
      return new Response(`\uFEFF${csv}`, {
        status: 200,
        headers: {
          "Content-Type": "text/csv; charset=utf-8",
          "Content-Disposition": `attachment; filename="wasteops-report-${from}-to-${to}.csv"`,
          "Cache-Control": "private, no-store",
        },
      });
    }
    const categorySummary: Array<[string, number, number]> = [...categoryTotals].map(([name, value]) => [
      name,
      value.kg,
      value.estimate,
    ]);
    const pdf = await renderToBuffer(
      buildPdf(
        rows,
        from,
        to,
        actor.fullName,
        generatedAt,
        { kg: totalKg, estimate: totalEstimate },
        [...zoneTotals].sort(([a], [b]) => a.localeCompare(b)),
        categorySummary.sort(([a], [b]) => a.localeCompare(b)),
        filterLabel,
      ),
    );
    await writeAudit(prisma, {
      organizationId: actor.organizationId,
      actorId: actor.id,
      action: "report.export.pdf",
      entityType: "Report",
      metadata: { from, to, zone: zone ?? null, category: category ?? null, rowCount: rows.length },
    });
    return new Response(new Uint8Array(pdf), {
      status: 200,
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="wasteops-report-${from}-to-${to}.pdf"`,
        "Cache-Control": "private, no-store",
      },
    });
  } catch {
    return NextResponse.json(
      { error: "Report generation failed; no complete export was produced." },
      { status: 503, headers: { "Cache-Control": "no-store" } },
    );
  }
}
